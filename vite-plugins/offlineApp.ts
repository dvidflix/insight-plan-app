import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Plugin } from 'vite';

/** The browser edition as an installable app that works offline: a web app manifest and a service worker that keeps every file
    of the build (including the WebAssembly) so the app opens with no network. Only in the web build (--mode web). */

const manifest = {
  name: 'Insight Plan',
  short_name: 'Insight Plan',
  description: '4D construction planning in the browser. Works offline once installed.',
  start_url: '/',
  scope: '/',
  display: 'standalone',
  background_color: '#ffffff',
  theme_color: '#0b5cad',
  icons: [{ src: '/favicon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' }],
};

const files = (dir: string): string[] => readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? files(join(dir, f)) : [join(dir, f)]));

const worker = (version: string, urls: string[]) => `// Generated by vite-plugins/offlineApp.ts
const CACHE = 'insight-plan-${version}';
const FILES = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => Promise.all(FILES.map((url) => cache.add(url)))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('insight-plan-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== location.origin || url.pathname.startsWith('/api/')) return;
  // The app is one page: any address opens the cached index.html.
  const key = request.mode === 'navigate' ? '/index.html' : request.url;
  event.respondWith(caches.match(key, { ignoreSearch: request.mode === 'navigate' }).then((hit) => hit || fetch(request)));
});
`;

export function offlineAppPlugin(): Plugin {
  let outDir = '';
  let root = '';
  return {
    name: 'insight-plan-offline-app',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir;
      root = config.root;
    },
    transformIndexHtml: () => [{ tag: 'link', attrs: { rel: 'manifest', href: '/manifest.webmanifest' }, injectTo: 'head' }],
    closeBundle() {
      const dir = join(root, outDir);
      writeFileSync(join(dir, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));
      const urls = ['/', ...files(dir).map((f) => '/' + relative(dir, f).replace(/\\/g, '/')).filter((u) => u !== '/sw.js' && !u.endsWith('.map'))].sort();
      // The version changes with the contents of the build, so an update replaces the kept files.
      const hash = createHash('sha256');
      for (const u of urls) if (u !== '/') hash.update(u).update(readFileSync(join(dir, u)));
      writeFileSync(join(dir, 'sw.js'), worker(hash.digest('hex').slice(0, 12), urls));
    },
  };
}
