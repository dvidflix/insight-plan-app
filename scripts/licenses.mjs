// Writes THIRD-PARTY-LICENSES.json (every production dependency with its licence, for the SBOM / the Help page) and
// public/THIRD-PARTY-NOTICES.txt (the same with each package's copyright notice, licence text and NOTICE file, which
// the MIT / BSD / Apache licences ask to travel with what is shipped). Run: npm run licenses
import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
const raw = JSON.parse(execSync('npx --yes license-checker-rseidelsohn --production --json', { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));
const entries = Object.entries(raw)
  .filter(([name]) => !name.startsWith('insight-plan-app@'))
  .sort((a, b) => a[0].localeCompare(b[0]));

writeFileSync('THIRD-PARTY-LICENSES.json', JSON.stringify(entries.map(([name, v]) => ({ name, licenses: v.licenses, repository: v.repository ?? null })), null, 2));
console.log(`${entries.length} packages written to THIRD-PARTY-LICENSES.json`);

const readText = (file) => {
  try {
    if (file && existsSync(file) && statSync(file).isFile()) return readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim();
  } catch {
    // unreadable: treated as missing
  }
  return null;
};
const rule = '='.repeat(78);
const parts = [
  'THIRD-PARTY NOTICES',
  '',
  'Insight Plan includes the open-source software below. Each package is used under the licence stated, and its copyright',
  'notice and licence text follow. Packages offered under a choice of licences are used under the permissive one (MIT, or',
  'Apache-2.0 where it is offered). MPL-2.0 packages are used unmodified; their source is at the repository given.',
  '',
  `${entries.length} packages. Generated by scripts/licenses.mjs.`,
  '',
];
const missing = [];
/** A package's own licence file text, when it has one (the tool falls back to the README otherwise). */
const ownLicenceText = (v) => {
  const isFile = !!v.licenseFile && /(licen[cs]e|copying)/i.test(v.licenseFile.split(/[\\/]/).pop() ?? '');
  const text = isFile ? readText(v.licenseFile) : null;
  return text && text.length < 60_000 ? text : null;
};
/** The standard text of a licence from another package that ships it, for packages that name the licence but ship no text. */
const standardText = (id) => {
  for (const [, o] of entries) if (o.licenses === id && ownLicenceText(o)) return ownLicenceText(o);
  return null;
};
const MIT = (holder) => `MIT License

Copyright (c) ${holder}

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.`;
for (const [name, v] of entries) {
  const text = readText(v.licenseFile);
  const notice = readText(v.noticeFile);
  parts.push(rule, name, `Licence: ${v.licenses}`);
  if (v.repository) parts.push(`Source: ${v.repository}`);
  if (v.publisher) parts.push(`Publisher: ${v.publisher}${v.email ? ` <${v.email}>` : ''}`);
  parts.push('');
  // Its own licence file; else the README's licence section; else the licence's standard text with the package's author
  // as copyright holder (said so in the file); else where to read it.
  const own = ownLicenceText(v);
  const readmeSection = !own && text ? /^#{1,3}\s*licen[cs]e[^\n]*\n([\s\S]*?)(?=\n#{1,3}\s|$)/im.exec(text)?.[1]?.trim() : null;
  const holder = v.publisher || v.repository?.replace(/^https?:\/\/(www\.)?github\.com\//, '').split('/')[0];
  if (own) parts.push(own);
  else if (readmeSection && readmeSection.length > 20) parts.push(`(From the package's README)
${readmeSection}`);
  else if (v.licenses === 'MIT' && holder) {
    missing.push(`${name} (standard MIT text)`);
    parts.push(`(The package names the MIT licence but ships no text. The standard MIT text follows, with the copyright holder taken from the package's own details.)

${MIT(holder)}`);
  } else if (standardText(v.licenses) && holder) {
    missing.push(`${name} (standard ${v.licenses} text)`);
    parts.push(`(The package names the ${v.licenses} licence but ships no text. The standard text follows; the copyright holder is ${holder}, taken from the package's own details.)

${standardText(v.licenses)}`);
  } else {
    missing.push(name);
    parts.push(`(The package ships no licence text. It is licensed under ${v.licenses}; see ${v.repository ?? 'its package page'}.)`);
  }
  if (notice) parts.push('', 'NOTICE:', notice);
  parts.push('');
}
mkdirSync('public', { recursive: true });
writeFileSync('public/THIRD-PARTY-NOTICES.txt', parts.join('\n'));
console.log(`public/THIRD-PARTY-NOTICES.txt written${missing.length ? `; no licence file, standard text used for: ${missing.join(', ')}` : ''}`);
